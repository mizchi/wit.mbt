"""Generate MoonBit acceptance tests from the pinned conformance corpus."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
corpus = json.loads((ROOT / "testdata/conformance.json").read_text())
text = '// Generated by scripts/generate-conformance-tests.py. Edit testdata/conformance.json.\n\n'
for case in corpus["cases"]:
    text += '///|\ntest "conformance: ' + case["name"] + '" {\n  let source =\n'
    text += ''.join('    #|' + line + '\n' for line in case["source"].split('\n'))
    text += '  @test.assert_eq(@wit.resolve(source) is Ok(_), ' + str(case["accepted"]).lower() + ')\n}\n\n'
path = ROOT / "src/conformance_test.mbt"
# Let MoonBit format its own generated syntax, including multiline-string spacing.
if args.check:
    # moon fmt can change layout without changing the corpus. A digest in the
    # generated header identifies its source independently of formatting.
    import hashlib
    expected = hashlib.sha256((ROOT / "testdata/conformance.json").read_bytes()).hexdigest()
    if ('// Corpus SHA256: ' + expected) not in path.read_text():
        raise SystemExit('Conformance tests are stale; run python3 scripts/generate-conformance-tests.py and just fmt')
else:
    import hashlib
    digest = hashlib.sha256((ROOT / "testdata/conformance.json").read_bytes()).hexdigest()
    text = '// Corpus SHA256: ' + digest + '\n' + text
    path.write_text(text.rstrip() + '\n')
